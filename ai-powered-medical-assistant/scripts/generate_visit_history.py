"""
Visit-history generator — deterministic, idempotent, 100% synthetic.

Builds data/visit_history.json: a longitudinal past-visit stream (plus lab
result sets) for every patient already in data/patients.json. It never adds
patients, doctors or appointments, and never touches the Medical Vault file
(data/medical_records.json).

Design rules (tests/test_visit_history.py proves each one):
  * Fixed seed, per-patient sub-seeds -> same inputs always give byte-identical
    output. Re-running simply rewrites the same file.
  * Every patients.json medical_history entry is reproduced verbatim as an
    "anchor" visit (same date, doctor, diagnosis, treatment, notes); generated
    visits are woven around those anchors, never after the patient's
    last_visit and never more than ~3 years before it.
  * Diagnoses come only from the patient's own condition set (the diagnoses in
    their medical_history). Acute visits are flare-ups / complications of
    those same conditions, not random new diseases.
  * Medication history is an event stream (start / adjust / short_course).
    Replaying it reproduces the patient's current_medications exactly, so no
    medication appears from nowhere. Short courses never persist.
  * A referral visit is always followed by that condition's next visit with
    the referred-to specialist.
  * ~40% of patients get 1-3 lab result sets attached to real visits, using
    the panel that fits the visit's condition and values that track the
    visit's control status (and any value quoted in the anchor note).

Usage:
    python scripts/generate_visit_history.py            # (re)write the file
    python scripts/generate_visit_history.py --check    # exit 1 if stale
"""
