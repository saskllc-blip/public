# Anchor notes that describe an active / under-treated condition.
UNCONTROLLED_WORDS = ["elevated", "adjustment may be needed", "episodes per month",
                      "% predicted", "uncontrolled", "follow-up in 3 months",
                      "fracture risk"]


def condition_key(diagnosis: str) -> str:
    d = diagnosis.lower()
    for key, spec in CONDITIONS.items():
        if any(m in d for m in spec["match"]):
            return key
    raise ValueError(f"No condition profile for diagnosis '{diagnosis}' — "
                     "extend CONDITIONS rather than dropping it.")


def anchor_status(notes: str) -> str:
    n = notes.lower()
    return "Uncontrolled" if any(w in n for w in UNCONTROLLED_WORDS) else "Controlled"


# ── Labs ──────────────────────────────────────────────────────────────────────
def _flag(value: float, low: Optional[float], high: Optional[float]) -> str:
    if low is not None and value < low:  return "Low"
    if high is not None and value > high: return "High"
    return "Normal"


def _note_number(notes: str, pattern: str) -> Optional[float]:
    m = re.search(pattern, notes, re.IGNORECASE)
    return float(m.group(1)) if m else None


def build_lab_results(panel: str, status: str, rng: random.Random,
                      notes: str) -> Tuple[str, List[Dict[str, Any]]]:
    """Return (panel name, results) whose values track the control status
    and honour any value quoted in an anchor note."""
    level = {"Newly diagnosed": 3, "Uncontrolled": 3, "Under evaluation": 3,
             "Improving": 2, "Controlled": 1}[status]

    def pick(bands: Dict[int, Tuple[float, float]], digits=1) -> float:
        lo, hi = bands[level]
        return round(rng.uniform(lo, hi), digits)

    def res(test, value, unit, low, high):
        ref = (f"{low}-{high}" if low is not None and high is not None
               else (f"<{high}" if high is not None else f">{low}"))
        return {"test": test, "value": value, "unit": unit,
                "reference_range": ref, "flag": _flag(value, low, high)}

    if panel == "a1c":
        a1c = _note_number(notes, r"HbA1c:\s*([\d.]+)") or pick(
            {3: (8.1, 9.0), 2: (7.3, 7.8), 1: (6.6, 7.1)})
        fpg = round(28.7 * a1c - 46.7 + rng.uniform(-8, 8))
        return "HbA1c & fasting glucose", [res("HbA1c", a1c, "%", None, 5.7),
                                           res("Fasting glucose", fpg, "mg/dL", 70, 100)]
    if panel == "renal":
        egfr = pick({3: (34, 42), 2: (40, 48), 1: (45, 55)}, 0)
        creat = round(118 / egfr * rng.uniform(0.95, 1.05), 2)
        return "Renal function panel", [res("Creatinine", creat, "mg/dL", 0.7, 1.3),
                                        res("eGFR", egfr, "mL/min/1.73m²", 60, None),
                                        res("Potassium", round(rng.uniform(4.3, 5.1), 1), "mmol/L", 3.5, 5.1)]
    if panel == "lipid":
        ldl = pick({3: (140, 165), 2: (120, 140), 1: (95, 118)}, 0)
        hdl = round(rng.uniform(38, 50))
        tg = pick({3: (170, 210), 2: (150, 175), 1: (120, 150)}, 0)
        return "Lipid panel", [res("Total cholesterol", round(ldl + hdl + tg / 5), "mg/dL", None, 200),
                               res("LDL", ldl, "mg/dL", None, 130),
                               res("HDL", hdl, "mg/dL", 40, None),
                               res("Triglycerides", tg, "mg/dL", None, 150)]
    if panel == "thyroid":
        tsh = _note_number(notes, r"TSH:\s*([\d.]+)") or pick(
            {3: (7.2, 11.5), 2: (4.4, 6.0), 1: (1.5, 3.5)})
        ft4 = round(max(0.5, 1.6 - tsh * 0.08 + rng.uniform(-0.05, 0.05)), 2)
        return "Thyroid panel", [res("TSH", tsh, "mIU/L", 0.4, 4.0),
                                 res("Free T4", ft4, "ng/dL", 0.8, 1.8)]
    if panel == "cbc":
        hb = _note_number(notes, r"Hemoglobin:\s*([\d.]+)") or pick(
            {3: (9.2, 10.2), 2: (10.8, 11.6), 1: (12.0, 12.8)})
        ferr = round(hb * 6 - 50 + rng.uniform(-4, 4))
        return "CBC & iron studies", [res("Haemoglobin", hb, "g/dL", 12.0, 15.5),
                                      res("Ferritin", max(ferr, 5), "ng/mL", 15, 150)]
    if panel == "inflammatory":
        esr = _note_number(notes, r"ESR[^\d]*([\d.]+)") or pick(
            {3: (38, 52), 2: (24, 34), 1: (12, 22)}, 0)
        crp = round(esr / 4 + rng.uniform(-1.5, 1.5), 1)
        return "Inflammatory markers", [res("ESR", esr, "mm/hr", None, 20),
                                        res("CRP", crp, "mg/L", None, 5.0)]
    if panel == "bone":
        vitd = pick({3: (14, 19), 2: (21, 27), 1: (30, 38)}, 0)
        return "Bone metabolism panel", [res("25-OH Vitamin D", vitd, "ng/mL", 30, 100),
                                         res("Serum calcium", round(rng.uniform(8.8, 9.8), 1), "mg/dL", 8.5, 10.5)]
    if panel == "spirometry":
        fev1 = _note_number(notes, r"FEV1:\s*([\d.]+)") or pick(
            {3: (66, 74), 2: (75, 80), 1: (81, 88)}, 0)
        return "Pulmonary function", [res("FEV1 % predicted", fev1, "%", 80, None)]
    raise ValueError(f"Unknown lab panel '{panel}'")


# ── Helpers ───────────────────────────────────────────────────────────────────
def _sub_rng(pid: str) -> random.Random:
    digest = hashlib.sha256(f"{SEED}:{pid}".encode()).hexdigest()
    return random.Random(int(digest[:16], 16))


def _d(s: str) -> date:
    return date.fromisoformat(s)


def _free_date(rng: random.Random, lo: date, hi: date, used: List[date]) -> Optional[date]:
    """Random date in [lo, hi] at least MIN_GAP_DAYS from every used date."""
    if hi < lo:
        return None
    span = (hi - lo).days
    for _ in range(200):
        cand = lo + timedelta(days=rng.randint(0, span))
        if all(abs((cand - u).days) >= MIN_GAP_DAYS for u in used):
            return cand
    return None


def _primary_doctor(anchors: List[Dict[str, Any]], doctors_by_name: Dict[str, Dict]) -> Dict:
    counts: Dict[str, int] = {}
    for a in anchors:
        counts[a["doctor"]] = counts.get(a["doctor"], 0) + 1
    top = max(counts.values())
    tied = [n for n, c in counts.items() if c == top]
    gps = [n for n in tied if doctors_by_name[n]["specialization"] == "General Physician"]
    if gps:
        return doctors_by_name[gps[0]]
    latest = max((a for a in anchors if a["doctor"] in tied), key=lambda a: a["date"])
    return doctors_by_name[latest["doctor"]]


# ── Per-patient generation ────────────────────────────────────────────────────
def generate_patient(patient: Dict[str, Any], doctors_by_name: Dict[str, Dict],
                     n_target: int, rng: random.Random) -> List[Dict[str, Any]]:
    pid      = patient["patient_id"]
    last     = _d(patient["last_visit"])
    anchors  = sorted(patient.get("medical_history", []), key=lambda a: a["date"])
    if not anchors:
        return []
    for a in anchors:
        if a["doctor"] not in doctors_by_name:
            raise ValueError(f"{pid}: anchor doctor '{a['doctor']}' not in doctors.json")
        if _d(a["date"]) > last:
            raise ValueError(f"{pid}: medical_history entry after last_visit")

    primary  = _primary_doctor(anchors, doctors_by_name)
    start    = last - timedelta(days=rng.randint(730, MAX_HISTORY_DAYS))
    conds    = {}                                  # cond key -> info
    for a in anchors:
        key = condition_key(a["diagnosis"])
        conds[key] = {"diagnosis": a["diagnosis"],
                      "manager": doctors_by_name[a["doctor"]],
                      "anchor": a}

    # Map each current medication to the condition that owns it.
    current = list(patient.get("current_medications", []))
    for med in current:
        owner = [k for k in conds for drug, _ in CONDITIONS[k]["drugs"] if med.startswith(drug)]
        if len(owner) != 1:
            raise ValueError(f"{pid}: current medication '{med}' does not map to exactly "
                             f"one of the patient's conditions ({owner})")

    used = [_d(a["date"]) for a in anchors]
    plan: List[Dict[str, Any]] = [
        {"date": _d(a["date"]), "cond": condition_key(a["diagnosis"]),
         "kind": "anchor", "anchor": a} for a in anchors]

    # Every condition gets one pre-anchor visit and, when its managing doctor
    # is not the primary doctor, one referral visit; n_target only grows to
    # make room for those.
    n_referrals = sum(1 for c in conds.values()
                      if c["manager"]["doctor_id"] != primary["doctor_id"])
    budget = max(n_target, 2 * len(anchors) + n_referrals) - len(anchors)

    def add(kind: str, cond: str, lo: date, hi: date) -> bool:
        nonlocal budget
        if budget <= 0:
            return False
        dt = _free_date(rng, lo, hi, used)
        if dt is None:
            return False
        used.append(dt)
        plan.append({"date": dt, "cond": cond, "kind": kind})
        budget -= 1
        return True

    # 1) One pre-anchor visit per condition, so dose titration happens before
    #    (not at) the anchor that says "continue current regimen".
    for key, c in conds.items():
        add("chronic", key, start, _d(c["anchor"]["date"]) - timedelta(days=MIN_GAP_DAYS))

    # 2) Referral for conditions managed by someone other than the primary
    #    doctor: a primary-doctor visit shortly before the condition's first
    #    visit, which then becomes the specialist consultation.
    for key, c in conds.items():
        if c["manager"]["doctor_id"] == primary["doctor_id"]:
            continue
        first = min(p["date"] for p in plan if p["cond"] == key)
        lo = max(start, first - timedelta(days=42))
        hi = first - timedelta(days=MIN_GAP_DAYS)
        add("referral", key, lo, hi)

    # 3) Remaining budget: more chronic follow-ups, occasionally an acute one.
    keys = list(conds)
    attempts = 0
    while budget > 0 and attempts < 50:
        attempts += 1
        key = rng.choice(keys)
        first = min(p["date"] for p in plan if p["cond"] == key and p["kind"] != "referral")
        acute_done = sum(1 for p in plan if p["kind"] == "acute")
        if rng.random() < ACUTE_PROBABILITY and acute_done < 2:
            add("acute", key, first + timedelta(days=MIN_GAP_DAYS), last - timedelta(days=1))
        else:
            add("chronic", key, first + timedelta(days=MIN_GAP_DAYS), last - timedelta(days=1))

    plan.sort(key=lambda p: p["date"])

    # ── Medication ladders: which visit of each condition takes which step ──
    steps_at: Dict[int, List[Tuple[str, Optional[str], str]]] = {}   # plan idx -> [(action, prev, med)]
    status_at: Dict[int, str] = {}
    for key, c in conds.items():
        idxs = [i for i, p in enumerate(plan) if p["cond"] == key and p["kind"] in ("chronic", "anchor")]
        anchor_idx = next(i for i in idxs if plan[i]["kind"] == "anchor")
        a_status = anchor_status(c["anchor"]["notes"])
        pre = [i for i in idxs if i < anchor_idx]
        # Steps may land on pre-anchor visits, plus the anchor itself when the
        # anchor note describes an uncontrolled condition (a dose step-up).
        slots = pre + ([anchor_idx] if a_status == "Uncontrolled" or not pre else [])
        for drug, ladder in CONDITIONS[key]["drugs"]:
            final = next((m for m in current if m.startswith(drug)), None)
            if final is None:
                continue                                   # patient isn't on it
            full = ladder + [final]
            # Start on the first slot; dose steps take the LAST slots so the
            # final step-up lands where the anchor note asks for it.
            s = max(0, len(full) - len(slots))
            steps_at.setdefault(slots[0], []).append(("start", None, full[s]))
            later = full[s + 1:]
            for j, med in enumerate(later):
                idx = slots[len(slots) - len(later) + j]
                prev = full[s + j]
                steps_at.setdefault(idx, []).append(("adjust", prev, med))
        # Control status per visit of this condition.
        prev_adjusted = False
        for n, idx in enumerate(idxs):
            acts = [a for a, _, _ in steps_at.get(idx, [])]
            if plan[idx]["kind"] == "anchor":
                st_ = a_status
            elif n == 0:
                st_ = "Newly diagnosed"
            elif "adjust" in acts:
                st_ = "Uncontrolled"
            elif prev_adjusted:
                st_ = "Improving"
            else:
                st_ = "Uncontrolled" if rng.random() < FLIP_PROBABILITY else "Controlled"
            status_at[idx] = st_
            prev_adjusted = "adjust" in acts

    # ── Build visit records ──────────────────────────────────────────────────
    sys_bp  = rng.randint(118, 128) + max(0, patient["age"] - 50) // 4
    dia_bp  = rng.randint(74, 80)
    hr_base = rng.randint(68, 80)
    bmi     = round(rng.uniform(22.0, 27.5) + (3.0 if "diabetes" in conds else 0.0), 1)

    active: List[str] = []
    cond_visit_no: Dict[str, int] = {}
    pending_referral: Dict[str, str] = {}
    visits: List[Dict[str, Any]] = []
    for i, p in enumerate(plan):
        key, spec = p["cond"], CONDITIONS[p["cond"]]
        c = conds[key]
        vid = f"VH-{pid}-{i + 1:02d}"
        med_changes: List[Dict[str, Any]] = []
        active_before = list(active)              # vitals reflect pre-visit state
        referral = None
        referred_from = None

        if p["kind"] == "referral":
            doctor, vtype, status = primary, "Referral", "Under evaluation"
            complaint = rng.choice(spec["complaints"])
            treatment = f"Referred to {c['manager']['name']} ({c['manager']['specialization']}) for {c['diagnosis']} management"
            referral = {"to_doctor_id": c["manager"]["doctor_id"],
                        "to_doctor_name": c["manager"]["name"],
                        "reason": f"Specialist assessment of {c['diagnosis']}"}
            pending_referral[key] = vid
        elif p["kind"] == "acute":
            doctor, vtype, status = primary, "Acute Visit", "Uncontrolled"
            complaint, treatment, course = rng.choice(spec["acute"])
            if course:
                med_changes.append({"action": "short_course", "medication": course, "previous": None})
        else:
            for action, prev, med in steps_at.get(i, []):
                med_changes.append({"action": action, "medication": med, "previous": prev})
                if prev:
                    active.remove(prev)
                active.append(med)
            status = status_at[i]
            cond_visit_no[key] = cond_visit_no.get(key, 0) + 1
            if p["kind"] == "anchor":
                doctor = doctors_by_name[p["anchor"]["doctor"]]
            elif key in pending_referral or c["manager"]["doctor_id"] == primary["doctor_id"]:
                doctor = c["manager"]
            else:
                doctor = c["manager"] if rng.random() < 0.6 else primary
            if key in pending_referral and doctor["doctor_id"] == c["manager"]["doctor_id"]:
                vtype = "Specialist Consultation"
                referred_from = pending_referral.pop(key)
            else:
                vtype = "Initial Consultation" if cond_visit_no[key] == 1 else "Follow-up"
            if p["kind"] == "anchor":
                complaint = rng.choice(spec["complaints"])
                treatment = p["anchor"]["treatment"]
            else:
                complaint = rng.choice(spec["complaints"])
                parts = []
                for mc in med_changes:
                    parts.append(f"Started {mc['medication']}" if mc["action"] == "start"
                                 else f"Adjusted {mc['previous']} -> {mc['medication']}")
                if not parts:
                    own = [m for m in active if any(m.startswith(d) for d, _ in spec["drugs"])]
                    parts.append("Continue " + ", ".join(own) if own else "Continue current plan")
                if status == "Uncontrolled" and not med_changes:
                    parts.append("adherence counselling, dose unchanged")
                treatment = "; ".join(parts) + f"; {spec['advice']}"

        # Vitals: drift plausibly along the timeline.
        bp_flare = status == "Uncontrolled" and key in ("hypertension", "ckd")
        htn_untreated = ("hypertension" in conds and
                         not any(m.startswith(("Amlodipine", "Lisinopril")) for m in active_before))
        sys_v = sys_bp + (22 if htn_untreated else 0) + (10 if bp_flare else 0)
        dia_v = dia_bp + (12 if htn_untreated else 0) + (6 if bp_flare else 0)
        sys_v += rng.randint(-4, 4); dia_v += rng.randint(-3, 3)
        hr_v = hr_base + rng.randint(-4, 4)
        if p["kind"] == "acute":
            hr_v += spec.get("hr_acute", 6)
        if status in ("Uncontrolled", "Newly diagnosed"):
            hr_v += spec.get("hr_uncontrolled", 0)
        if any(m.startswith("Propranolol") for m in active_before):
            hr_v -= 8                                      # beta-blocker effect
        if p["kind"] == "anchor":
            m = re.search(r"(\d{2,3})/(\d{2,3})", p["anchor"]["notes"])
            if m:
                sys_v, dia_v = int(m.group(1)), int(m.group(2))
        if "diabetes" in conds:
            bmi = round(bmi + CONDITIONS["diabetes"]["bmi_trend"] + rng.uniform(-0.1, 0.1), 1)
        else:
            bmi = round(bmi + rng.uniform(-0.15, 0.15), 1)

        if p["kind"] == "anchor":
            notes = p["anchor"]["notes"]
        else:
            notes = (f"{status}. BP {sys_v}/{dia_v}, HR {hr_v}, BMI {bmi}. "
                     + {"Referral": "Specialist input requested.",
                        "Acute Visit": "Acute episode on background of known condition; review at next follow-up.",
                        "Specialist Consultation": "Seen on referral; plan shared with primary doctor.",
                        }.get(vtype, "Review in 3 months."))

        visits.append({
            "visit_id":        vid,
            "patient_id":      pid,
            "patient_name":    patient["name"],
            "doctor_id":       doctor["doctor_id"],
            "doctor_name":     doctor["name"],
            "specialization":  doctor["specialization"],
            "date":            p["date"].isoformat(),
            "visit_type":      vtype,
            "status":          "Completed",
            "chief_complaint": complaint,
            "diagnosis":       c["diagnosis"],
            "control_status":  status,
            "treatment":       treatment,
            "medication_changes": med_changes,
            "vitals": {"bp_systolic": sys_v, "bp_diastolic": dia_v,
                       "heart_rate": hr_v, "bmi": bmi},
            "notes":           notes,
            "referral":        referral,
            "referred_from_visit_id": referred_from,
            "source":          "patients.json medical_history" if p["kind"] == "anchor" else "generated",
        })

    if sorted(active) != sorted(current):
        raise AssertionError(f"{pid}: replayed medications {active} != current {current}")
    return visits


def attach_labs(visits: List[Dict[str, Any]], rng: random.Random) -> List[Dict[str, Any]]:
    eligible = [v for v in visits
                if v["visit_type"] not in ("Referral", "Acute Visit")
                and CONDITIONS[condition_key(v["diagnosis"])]["lab"]]
    if not eligible:
        return []
    # Visits whose (anchor) note already quotes a lab value come first.
    quoted = [v for v in eligible if v["source"] != "generated" and re.search(r"\d", v["notes"])
              and re.search(r"HbA1c|TSH|Hemoglobin|ESR|FEV1", v["notes"])]
    others = [v for v in eligible if v not in quoted]
    rng.shuffle(others)
    n = min(rng.randint(1, 3), len(eligible))
    chosen = sorted((quoted + others)[:n], key=lambda v: v["date"])
    labs = []
    for k, v in enumerate(chosen, 1):
        panel_key = CONDITIONS[condition_key(v["diagnosis"])]["lab"]
        notes = v["notes"] if v["source"] != "generated" else ""
        panel, results = build_lab_results(panel_key, v["control_status"], rng, notes)
        labs.append({"lab_id": f"LB-{v['patient_id']}-{k:02d}",
                     "visit_id": v["visit_id"], "patient_id": v["patient_id"],
                     "date": v["date"], "condition": v["diagnosis"],
                     "panel": panel, "results": results})
    return labs


# ── Dataset ───────────────────────────────────────────────────────────────────
def build_dataset(data_dir: str = DATA_DIR) -> Dict[str, Any]:
    with open(os.path.join(data_dir, "patients.json")) as f:
        patients = json.load(f)
    with open(os.path.join(data_dir, "doctors.json")) as f:
        doctors = json.load(f)
    doctors_by_name = {d["name"]: d for d in doctors}

    visits: List[Dict[str, Any]] = []
    per_patient: Dict[str, List[Dict[str, Any]]] = {}
    for p in sorted(patients, key=lambda x: x["patient_id"]):
        rng = _sub_rng(p["patient_id"])
        sizes, weights = zip(*VISIT_COUNT_WEIGHTS.items())
        n_target = rng.choices(sizes, weights=weights)[0]
        pv = generate_patient(p, doctors_by_name, n_target, rng)
        per_patient[p["patient_id"]] = pv
        visits.extend(pv)

    # ~40% of patients get labs; sicker (more lab-relevant conditions) first.
    lab_rng = _sub_rng("labs")
    ranked = []
    for pid, pv in per_patient.items():
        lab_conds = {v["diagnosis"] for v in pv
                     if CONDITIONS[condition_key(v["diagnosis"])]["lab"]}
        if lab_conds:
            ranked.append((-len(lab_conds), lab_rng.random(), pid))
    ranked.sort()
    k = round(LAB_PATIENT_SHARE * len(patients))
    lab_results: List[Dict[str, Any]] = []
    for _, _, pid in ranked[:k]:
        lab_results.extend(attach_labs(per_patient[pid], _sub_rng(f"labs:{pid}")))

    return {
        "schema_version": SCHEMA_VERSION,
        "disclaimer": DISCLAIMER,
        "generator": {
            "script": "scripts/generate_visit_history.py",
            "seed": SEED,
            "target_visits_per_patient": round(TARGET_VISITS_PER_PATIENT, 2),
            "patients": len(patients),
            "doctors": len(doctors),
        },
        "visits": visits,
        "lab_results": lab_results,
    }


def render(dataset: Dict[str, Any]) -> str:
    return json.dumps(dataset, indent=2, ensure_ascii=False) + "\n"


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the committed file differs from a fresh build")
    ap.add_argument("--out", default=OUT_FILE)
    args = ap.parse_args(argv)

    text = render(build_dataset())
    if args.check:
        existing = open(args.out).read() if os.path.exists(args.out) else ""
        ok = existing == text
        print("visit_history.json is up to date" if ok else "visit_history.json is STALE")
        return 0 if ok else 1
    with open(args.out, "w") as f:
        f.write(text)
    ds = json.loads(text)
    print(f"Wrote {len(ds['visits'])} visits, {len(ds['lab_results'])} lab sets "
          f"-> {os.path.relpath(args.out, APP_DIR)} "
          f"(sha256 {hashlib.sha256(text.encode()).hexdigest()[:16]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
