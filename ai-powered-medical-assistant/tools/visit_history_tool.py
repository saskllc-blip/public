"""
Visit History Tool — read-only access to the longitudinal past-visit store.
Data lives in data/visit_history.json (generated by
scripts/generate_visit_history.py), deliberately separate from the Medical
Vault's data/medical_records.json. Every visit and lab set carries its own
unique id; the views render them as tables, so no per-record widget keys.
"""
import json, os, sys, time
from typing import Any, Dict, List

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import config
from utils.logger import log_tool_call


def _load() -> Dict[str, Any]:
    if not os.path.exists(config.VISIT_HISTORY_FILE):
        return {"visits": [], "lab_results": []}
    with open(config.VISIT_HISTORY_FILE) as f: return json.load(f)


def replay_medications(visits: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Replay medication_changes in date order. Short courses never persist."""
    active: List[str] = []
    events: List[Dict[str, Any]] = []
    for v in sorted(visits, key=lambda x: x["date"]):
        for mc in v.get("medication_changes", []):
            if mc["action"] == "adjust" and mc.get("previous") in active:
                active.remove(mc["previous"])
            if mc["action"] in ("start", "adjust"):
                active.append(mc["medication"])
            events.append({"date": v["date"], "visit_id": v["visit_id"],
                           "doctor": v["doctor_name"], "action": mc["action"],
                           "medication": mc["medication"], "previous": mc.get("previous")})
    return {"active": active, "events": events}


def get_patient_visits(patient_id: str) -> Dict[str, Any]:
    start = time.time()
    try:
        data   = _load()
        visits = sorted((v for v in data["visits"] if v["patient_id"] == patient_id),
                        key=lambda v: v["date"], reverse=True)
        labs   = sorted((l for l in data["lab_results"] if l["patient_id"] == patient_id),
                        key=lambda l: l["date"], reverse=True)
        result = {"success": True, "patient_id": patient_id, "visits": visits,
                  "lab_results": labs, "medications": replay_medications(visits)}
        log_tool_call("get_patient_visits", patient_id, f"{len(visits)} visits", True,
                      duration_ms=(time.time()-start)*1000, patient_id=patient_id)
        return result
    except Exception as e:
        log_tool_call("get_patient_visits", patient_id, str(e), False,
                      error=str(e), duration_ms=(time.time()-start)*1000)
        return {"success": False, "error": str(e)}


def get_doctor_visits(doctor_id: str) -> Dict[str, Any]:
    start = time.time()
    try:
        data   = _load()
        visits = sorted((v for v in data["visits"] if v["doctor_id"] == doctor_id),
                        key=lambda v: v["date"], reverse=True)
        result = {"success": True, "doctor_id": doctor_id, "visits": visits,
                  "unique_patients": len({v["patient_id"] for v in visits}),
                  "referrals_received": sum(1 for v in visits if v.get("referred_from_visit_id"))}
        log_tool_call("get_doctor_visits", doctor_id, f"{len(visits)} visits", True,
                      duration_ms=(time.time()-start)*1000)
        return result
    except Exception as e:
        log_tool_call("get_doctor_visits", doctor_id, str(e), False,
                      error=str(e), duration_ms=(time.time()-start)*1000)
        return {"success": False, "error": str(e)}


def format_visit_timeline(visits: List[Dict[str, Any]]) -> str:
    """Compact text timeline (most recent first) for the EHR history text."""
    lines = []
    for v in sorted(visits, key=lambda x: x["date"], reverse=True):
        meds = "; ".join(
            (f"{m['action']}: {m['previous']} -> {m['medication']}" if m.get("previous")
             else f"{m['action']}: {m['medication']}") for m in v.get("medication_changes", []))
        vt = v["vitals"]
        lines.append(f"  [{v['date']}] {v['visit_type']} — {v['diagnosis']} "
                     f"({v['control_status']}) · {v['doctor_name']}\n"
                     f"    Complaint: {v['chief_complaint']} · BP {vt['bp_systolic']}/"
                     f"{vt['bp_diastolic']}, HR {vt['heart_rate']}, BMI {vt['bmi']}"
                     + (f"\n    Medication: {meds}" if meds else ""))
    return "\n".join(lines)
